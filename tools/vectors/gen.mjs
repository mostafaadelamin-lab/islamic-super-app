const keys = ["fajr", "sunrise", "dhuhr", "asr", "maghrib", "isha"];
const fmt = (d, tz) => new Intl.DateTimeFormat("en-GB", { timeZone: tz, hour: "2-digit", minute: "2-digit", hourCycle: "h23" }).format(d);
const out = [];
for (const [city, cc, lat, lng, tz, method, dates] of cases) {
  for (const date of dates) for (const asrKey of (city === "Karachi" || city === "Istanbul") ? ["standard", "hanafi"] : ["standard"]) {
    const m = M.methods[method];
    const p = new adhan.CalculationParameters("Other", m.fajr, m.isha ?? 0, m.ishaMinutes ?? 0);
    p.madhab = asrKey === "hanafi" ? adhan.Madhab.Hanafi : adhan.Madhab.Shafi;
    p.highLatitudeRule = adhan.HighLatitudeRule.TwilightAngle;
    p.adjustments.dhuhr = M.dhuhrOffsetMinutes;
    const [y, mo, d] = date.split("-").map(Number);
    // adhan interprets the Date's local Y/M/D; the container runs in UTC.
    const t = new adhan.PrayerTimes(new adhan.Coordinates(lat, lng), new Date(y, mo - 1, d), p);
    const local = {}, utc = {};
    for (const k of keys) { local[k] = fmt(t[k], tz); utc[k] = t[k].toISOString().slice(0, 16) + "Z"; }
    out.push({ id: `${city.replace(/ /g, "")}-${date}-${method}-${asrKey}`, city, country: cc, lat, lng, tz, date, method, asr: asrKey, local, utc });
  }
}
