/// Plays clips of one recording.
abstract class DrivePlayer {
  /// [source]: a file on the phone (or a bundled asset "assets/...").
  Future<void> load(String source);

  /// Plays [clip] once. Completes when it ended or [stop] was called.
  Future<void> playClip(DriveClip clip);
  Future<void> stop();
  Future<void> dispose();
}

/// The sounds between repetitions and the spoken count.
abstract class DriveCues {
  /// Soft sound between two repetitions.
  Future<void> tick();

  /// A different sound when a dhikr is complete.
  Future<void> done();

  /// Says [n] (the repetitions done so far) out loud.
  Future<void> say(int n, {required bool arabic});
  Future<void> dispose();
}

class JustAudioDrivePlayer implements DrivePlayer {
  final _p = AudioPlayer();
  Completer<void>? _clip;
  StreamSubscription<PlayerState>? _sub;

  @override
  Future<void> load(String source) async {
    await (source.startsWith('assets/') ? _p.setAsset(source) : _p.setFilePath(source));
    _sub ??= _p.playerStateStream.listen((s) {
      if (s.processingState == ProcessingState.completed) _finish();
    });
  }

  void _finish() {
    final c = _clip;
    _clip = null;
    if (c != null && !c.isCompleted) c.complete();
  }

  @override
  Future<void> playClip(DriveClip clip) async {
    _finish();
    final c = _clip = Completer<void>();
    await _p.setClip(start: clip.start, end: clip.end);
    await _p.seek(Duration.zero);
    unawaited(_p.play());
    return c.future;
  }

  @override
  Future<void> stop() async {
    _finish();
    await _p.pause();
  }

  @override
  Future<void> dispose() async {
    _finish();
    await _sub?.cancel();
    await _p.dispose();
  }
}

/// Cue sounds are the app's own short tones (assets/audio/drive_*.wav, generated by
/// tools/drive_tones.py); the count is spoken by the phone's text-to-speech voice.
class DeviceDriveCues implements DriveCues {
  final _tick = AudioPlayer();
  final _done = AudioPlayer();
  FlutterTts? _tts;
  bool _loaded = false;

  Future<void> _load() async {
    if (_loaded) return;
    _loaded = true;
    await _tick.setAsset('assets/audio/drive_tick.wav');
    await _done.setAsset('assets/audio/drive_done.wav');
  }

  Future<void> _play(AudioPlayer p) async {
    try {
      await _load();
      await p.seek(Duration.zero);
      await p.play();
      await p.pause();
    } catch (e) {
      debugPrint('drive cue: $e');
    }
  }

  @override
  Future<void> tick() => _play(_tick);
  @override
  Future<void> done() => _play(_done);

  @override
  Future<void> say(int n, {required bool arabic}) async {
    try {
      var t = _tts;
      if (t == null) {
        t = _tts = FlutterTts();
        // iOS: keep the app's music audio session as it is, so the app stays the
        // "Now Playing" app on the lock screen and in CarPlay.
        if (defaultTargetPlatform == TargetPlatform.iOS) await t.autoStopSharedSession(false);
      }
      await t.awaitSpeakCompletion(true);
      await t.setLanguage(arabic ? 'ar' : 'en-US');
      await t.setSpeechRate(0.45);
      await t.speak(arabic ? toArabicIndic(n) : '$n');
    } catch (e) {
      debugPrint('drive tts: $e');
      await tick();
    }
  }

  @override
  Future<void> dispose() async {
    await _tick.dispose();
    await _done.dispose();
    await _tts?.stop();
  }
}

/// Driving mode: plays the morning or evening adhkar with no touching, each dhikr
/// repeated its Hisn al-Muslim count, and shows the count on the lock screen, in the
/// notification and on the car screen (Android Auto / CarPlay "Now Playing").
/// Buttons there, on the steering wheel and on headsets: next = next dhikr,
/// previous = this dhikr from the start (again: the dhikr before), play/pause keeps the count.
class DriveModeController extends ChangeNotifier implements MediaSource {
  DriveModeController({
    required AppContent content,
    required SettingsController settings,
    required AdhkarAudioFiles files,
    required Future<DriveClips?> Function() clips,
    DrivePlayer Function()? player,
    DriveCues Function()? cues,
  }) : _content = content,
       _settings = settings,
       _files = files,
       _loadClips = clips,
       _newPlayer = player ?? JustAudioDrivePlayer.new,
       _newCues = cues ?? DeviceDriveCues.new {
    AudioFocus.register(this, () {
      if (_playing) pause();
    });
  }

  /// Reads assets/content/adhkar-drive.v1.json from [bundle].
  static Future<DriveClips?> Function() assetClips(AssetBundle bundle) {
    DriveClips? cached;
    return () async {
      if (cached != null) return cached;
      try {
        cached = DriveClips.fromJson(jsonDecode(await bundle.loadString(DriveClips.asset)) as Map<String, dynamic>);
      } catch (e) {
        debugPrint('drive clips: $e');
      }
      return cached;
    };
  }

  final AppContent _content;
  final SettingsController _settings;
  final AdhkarAudioFiles _files;
  final Future<DriveClips?> Function() _loadClips;
  final DrivePlayer Function() _newPlayer;
  final DriveCues Function() _newCues;
  DrivePlayer? _player;
  DriveCues? _cues;

  AdhkarSession? _session;
  String? _main;
  Map<String, String> _paths = const {};
  String? _loaded;
  List<DriveItem> _items = const [];
  int _index = 0;
  int _done = 0;
  bool _playing = false;
  bool _preparing = false;
  bool _failed = false;
  bool _finished = false;

  /// Time since the current repetition started.
  final _sinceRep = Stopwatch();

  /// Bumped by every jump / pause / stop; a running loop whose number is old stops.
  int _run = 0;

  /// While a long dhikr is said, moves the car title on to the next part of its text.
  Timer? _ticker;
  int _shownPart = 0;
  final _partsCache = <String, List<String>>{};

  AdhkarSession? get session => _session;
  List<DriveItem> get items => _items;
  int get index => _index;
  DriveItem? get current => _index < _items.length ? _items[_index] : null;

  /// Repetitions of the current dhikr already said.
  int get done => _done;

  /// The whole text of the current dhikr in parts short enough for the car's title.
  List<String> get parts {
    final item = current;
    if (item == null) return const [];
    return _partsCache.putIfAbsent(item.dhikr.text, () => driveParts(item.dhikr.text));
  }

  /// The part of [parts] being said now (follows the recording while it plays).
  int get part {
    final item = current;
    final p = parts;
    if (item == null || p.length <= 1 || !_playing) return 0;
    final len = item.clip.length.inMilliseconds;
    if (len <= 0) return 0;
    return drivePartAt(p, _sinceRep.elapsedMilliseconds / len);
  }

  /// The current dhikr's whole text in short lines, for the car's «نص الذكر» screen.
  List<String> textLines() {
    final item = current;
    return item == null ? const [] : driveParts(item.dhikr.text, maxLetters: 30);
  }

  void _tick() {
    final now = part;
    if (now == _shownPart) return;
    _shownPart = now;
    notifyListeners();
  }

  void _startTicker() {
    _ticker ??= Timer.periodic(const Duration(milliseconds: 300), (_) => _tick());
  }

  void _stopTicker() {
    _ticker?.cancel();
    _ticker = null;
    _shownPart = 0;
  }

  /// The repetition being said now (1-based), as the car screen shows it.
  int get saying => current == null ? 0 : (_done + (_done < current!.count ? 1 : 0));
  bool get isPlaying => _playing;

  /// Downloading the recording (first time) or loading it.
  bool get isPreparing => _preparing;

  /// The recording could not be downloaded.
  bool get failed => _failed;

  /// Every dhikr is done.
  bool get finished => _finished;
  bool get isActive => _session != null;

  /// Starts [session] from its first dhikr (or goes on where it is when it is already loaded).
  Future<void> start(AdhkarSession session) async {
    if (_session == session && _items.isNotEmpty && !_failed) {
      if (_finished) {
        _index = 0;
        _done = 0;
        _finished = false;
      }
      return resume();
    }
    await _halt();
    _session = session;
    _items = const [];
    _index = 0;
    _done = 0;
    _finished = false;
    _failed = false;
    _preparing = true;
    notifyListeners();
    final run = _run;
    try {
      final clips = await _loadClips();
      final file = clips?.sessions[session]?.file;
      if (clips == null || file == null) throw StateError('no clips');
      final items = drivePlan(_content.adhkar, clips, session);
      // Every recording the session uses (normally one), downloaded before starting.
      final paths = <String, String>{};
      for (final f in {file, for (final it in items) ?it.clip.file}) {
        final p = await _files.fetch(f);
        if (p == null) throw StateError('recording $f not available');
        paths[f] = p;
      }
      if (run != _run) return;
      _items = items;
      _main = file;
      _paths = paths;
      _loaded = null;
      _preparing = false;
      notifyListeners();
      await resume();
    } catch (e) {
      debugPrint('drive mode: $e');
      if (run != _run) return;
      _preparing = false;
      _failed = true;
      notifyListeners();
    }
  }

  Future<void> resume() async {
    if (_items.isEmpty || _playing || _preparing) return;
    if (_finished) return;
    _playing = true;
    AudioFocus.claim(this);
    _startTicker();
    notifyListeners();
    // Runs on its own; the caller does not wait for the whole session.
    unawaited(_loop(++_run));
  }

  Future<void> pause() async {
    if (!_playing) return;
    _playing = false;
    _run++;
    _sinceRep.stop();
    _stopTicker();
    notifyListeners();
    await _player?.stop();
  }

  Future<void> toggle() => _playing ? pause() : (_session == null ? Future.value() : start(_session!));

  /// Next dhikr.
  Future<void> next() => _jump(_index + 1);

  /// The current dhikr from its first repetition. Pressed again within 3 seconds (it is still
  /// on its first repetition), the dhikr before.
  Future<void> previous() {
    final early = _done == 0 && (!_playing || _sinceRep.elapsed < const Duration(seconds: 3));
    return early && _index > 0 ? _jump(_index - 1) : _jump(_index);
  }

  /// Jumps to the dhikr at [i] (its count starts again).
  Future<void> jumpTo(int i) => _jump(i);

  Future<void> _jump(int i) async {
    if (_items.isEmpty) return;
    final was = _playing || _finished;
    await _halt();
    _index = i.clamp(0, _items.length - 1);
    _done = 0;
    _finished = false;
    notifyListeners();
    if (was) await resume();
  }

  Future<void> stop() async {
    await _halt();
    _session = null;
    _items = const [];
    _index = 0;
    _done = 0;
    _finished = false;
    _failed = false;
    _preparing = false;
    notifyListeners();
  }

  Future<void> _halt() async {
    _run++;
    _playing = false;
    _sinceRep.stop();
    _stopTicker();
    await _player?.stop();
  }

  Future<void> _loop(int run) async {
    final cues = _cues ??= _newCues();
    while (run == _run && _index < _items.length) {
      final item = _items[_index];
      if (_done >= item.count) {
        if (_index == _items.length - 1) break;
        _index++;
        _done = 0;
        notifyListeners();
        continue;
      }
      _sinceRep
        ..reset()
        ..start();
      _shownPart = 0;
      final f = item.clip.file ?? _main!;
      final player = _player ??= _newPlayer();
      if (_loaded != f) {
        await player.load(_paths[f]!);
        _loaded = f;
        if (run != _run) return;
      }
      await player.playClip(item.clip);
      if (run != _run) return;
      _done++;
      notifyListeners();
      if (_done >= item.count) {
        if (_settings.driveCues) await cues.done();
      } else if (isMilestone(_done, item.count, _settings.driveSayEvery)) {
        await cues.say(_done, arabic: _settings.isArabic);
      } else if (_settings.driveCues) {
        await cues.tick();
      }
    }
    if (run != _run) return;
    _playing = false;
    _stopTicker();
    _finished = true;
    notifyListeners();
  }

  // ---- Lock screen / notification / car screen ----

  @override
  NowPlaying? describe() {
    final s = _session;
    final item = current;
    if (s == null || item == null) return null;
    final ar = _settings.isArabic;
    String n(int x) => ar ? toArabicIndic(x) : '$x';
    final count = item.count == 1
        ? ''
        : (ar ? 'المرة ${n(saying)} من ${n(item.count)} · ' : 'Time ${n(saying)} of ${n(item.count)} · ');
    final when = s == AdhkarSession.morning ? (ar ? 'أذكار الصباح' : 'Morning adhkar') : (ar ? 'أذكار المساء' : 'Evening adhkar');
    // The car shows two lines of the title: the whole dhikr goes by part after part with the
    // recording (owner 2026-11-23: it was cut after a few words). The count is on the line below.
    final p = parts;
    return NowPlaying(
      id: 'drive/${s.name}/$_index',
      title: drivePartTitle(p, part.clamp(0, p.length - 1)),
      artist: ar
          ? '$count$when · ${n(_index + 1)} من ${n(_items.length)}'
          : '$count$when · ${n(_index + 1)} of ${n(_items.length)}',
      playing: _playing,
    );
  }

  @override
  void act(String action) {
    switch (action) {
      case 'play':
        unawaited(resume());
      case 'pause':
        unawaited(pause());
      case 'next':
        unawaited(next());
      case 'previous':
        unawaited(previous());
      case 'stop':
        unawaited(stop());
    }
  }

  @override
  void dispose() {
    AudioFocus.unregister(this);
    _run++;
    _stopTicker();
    unawaited(_player?.dispose());
    unawaited(_cues?.dispose());
    super.dispose();
  }
}

/// Android Auto: the app's list on the car screen. Two items, the morning and the evening
/// adhkar in driving mode; picking one starts it (Now Playing then shows the count).
class DriveBrowser implements MediaBrowser {
  DriveBrowser(this.drive, this.settings);
  final DriveModeController drive;
  final SettingsController settings;

  static const morningId = 'drive/morning';
  static const eveningId = 'drive/evening';

  @override
  Future<List<MediaItem>> children(String parentId) async {
    if (parentId != AudioService.browsableRootId && parentId != AudioService.recentRootId) return const [];
    final ar = settings.isArabic;
    final items = [
      MediaItem(
        id: morningId,
        title: ar ? 'أذكار الصباح' : 'Morning adhkar',
        artist: ar ? 'وضع القيادة · العدّ تلقائي' : 'Driving mode · counted for you',
        playable: true,
      ),
      MediaItem(
        id: eveningId,
        title: ar ? 'أذكار المساء' : 'Evening adhkar',
        artist: ar ? 'وضع القيادة · العدّ تلقائي' : 'Driving mode · counted for you',
        playable: true,
      ),
    ];
    if (parentId == AudioService.recentRootId) {
      final s = drive.session;
      return s == null ? const [] : [items[s == AdhkarSession.morning ? 0 : 1]];
    }
    return items;
  }

  @override
  Future<void> play(String id) async {
    if (id == morningId) await drive.start(AdhkarSession.morning);
    if (id == eveningId) await drive.start(AdhkarSession.evening);
  }
}
