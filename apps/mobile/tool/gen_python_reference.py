#!/usr/bin/env python3
"""Writes test/fixtures/prayer_python_reference.json: the output of the reference
implementation (services/api/app/domain/prayer.py) for every case in
tests/vectors/prayer-times.json plus a few extra cases (adjustments, hanafi,
high latitude). The Dart port must match these to the minute.
Run from the repo root: python3 apps/mobile/tool/gen_python_reference.py
"""
import json
import pathlib
import sys
from datetime import date

ROOT = pathlib.Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / "services/api"))
from app.domain import prayer  # noqa: E402

vec = json.loads((ROOT / "tests/vectors/prayer-times.json").read_text(encoding="utf-8"))
cases = [dict(c, adjustments={}) for c in vec["cases"]]
cases += [
    {"id": "extra-cairo-adjusted", "lat": 30.0444, "lng": 31.2357, "tz": "Africa/Cairo", "date": "2026-11-06",
     "method": "egypt", "asr": "hanafi", "adjustments": {"fajr": -30, "dhuhr": 2, "isha": 30}},
    {"id": "extra-oslo-makkah-summer", "lat": 59.9139, "lng": 10.7522, "tz": "Europe/Oslo", "date": "2026-06-21",
     "method": "makkah", "asr": "standard", "adjustments": {}},
    {"id": "extra-sydney-qatar", "lat": -33.8688, "lng": 151.2093, "tz": "Australia/Sydney", "date": "2026-01-01",
     "method": "qatar", "asr": "hanafi", "adjustments": {}},
    {"id": "extra-dubai-leap", "lat": 25.2048, "lng": 55.2708, "tz": "Asia/Dubai", "date": "2028-02-29",
     "method": "dubai", "asr": "standard", "adjustments": {}},
]
out = []
for c in cases:
    d = date.fromisoformat(c["date"])
    r = prayer.prayer_times(d, c["lat"], c["lng"], c["method"], c["asr"], c["adjustments"])
    out.append({
        "id": c["id"], "lat": c["lat"], "lng": c["lng"], "tz": c["tz"], "date": c["date"],
        "method": c["method"], "asr": c["asr"], "adjustments": c["adjustments"],
        "utc": {k: v.strftime("%Y-%m-%dT%H:%MZ") for k, v in r.as_dict().items()},
        "local": {k: prayer.local_hhmm(v, c["tz"]) for k, v in r.as_dict().items()},
        "highLatitudeAdjusted": list(r.high_latitude_adjusted),
    })
qibla = [{"lat": q["lat"], "lng": q["lng"], "bearing": prayer.qibla_bearing(q["lat"], q["lng"])} for q in vec["qibla"]]
dst = ROOT / "apps/mobile/test/fixtures/prayer_python_reference.json"
dst.write_text(json.dumps({"_note": "Generated by apps/mobile/tool/gen_python_reference.py from services/api/app/domain/prayer.py. Do not edit.",
                           "cases": out, "qibla": qibla}, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
print(f"wrote {dst} ({len(out)} cases)")
